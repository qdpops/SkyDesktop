//! Адрес управляющей точки менеджера подключений.
//!
//! Реестр подключений живёт в процессе менеджера (`--cm`), поэтому панель не
//! может закрыть сеанс сама: её вызов не нашёл бы нужного подключения.
//! Менеджер сообщает панели свой адрес вместе со списком подключений, а
//! панель шлёт туда команду разрыва.

use std::sync::{Mutex, OnceLock};

fn cell() -> &'static Mutex<String> {
    static CELL: OnceLock<Mutex<String>> = OnceLock::new();
    CELL.get_or_init(|| Mutex::new(String::new()))
}

/// Запоминает адрес, присланный менеджером подключений.
pub fn set(url: String) {
    *cell().lock().unwrap() = url;
}

/// Адрес менеджера; пусто — подключений сейчас нет.
pub fn get() -> String {
    cell().lock().unwrap().clone()
}
